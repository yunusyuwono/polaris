<center class="judul">BAB I PENDAHULUAN</center>
<hr>
<div>
    <b>A. LATAR BELAKANG</b>
</div>
<div style="margin-left: 14pt;">
<p class="para">
Tuntutan masyarakat terhadap kualitas pendidikan tinggi saat ini semakin menjadi pacuan bagi
setiap institusi pendidikan tinggi meningkatkan mutu akademik beserta pelayanannya. Pemerintah
juga memperkuat hal ini dengan mengeluarkan berbagai undang-undang dan peraturan yaitu
Permendikbud RI Nomor 3 tahun 2020 tentang Standar Nasional Pendidikan Tinggi, Undang-undang
Nomor 20 tahun 2003 tentang sistem pendidikan nasional, Undang-undang Nomor 14 tahun 2005
tentang Guru dan Dosen, Peraturan Pemerintah Nomor 60 Tahun 2005 tentang perguruan tinggi,
Peraturan Pemerintah Nomor 19 tahun 2005 tentang standar pendidikan tinggi, dan Higher Education
Long Term Strategy 2003-2010 dan Pedoman Penjaminan Mutu Pendidikan Tinggi tahun 2003.
</p>
<p class="para">Poltekkes Kemenkes Bengkulu merupakan perguruan tinggi kesehatan negeri yang terus
berusaha untuk meningkatkan kualitas baik dalam segi mutu akademik maupun pelayanan
administrasi bagi civitas akademik itu sendiri. Salah satu misi Poltekkes Kemenkes Bengkulu yaitu
Meningkatkan kwalitas dan kwantitas SDM serta sarana dan prasarana pendidikan. Menyikapi kondisi
ini, sudah seyogyanya Poltekkes Kemenkes Bengkulu mengembangkan sistem penjaminan mutu dan
melakukan pengendalian internal dengan melaksanakan audit mutu akademik. Terkait dengan
peningkatan mutu input, proses dan output pendidikan serta pengembangan sistem penjaminan mutu
akademik di Poltekkes Kemenkes Bengkulu, maka diperlukan suatu audit internal bidang akademik.
Kegiatan audit internal bidang akademik merupakan salah satu bentuk monitoring dan evaluasi yang
dilakukan terhadap capaian maupun target-target yang telah ditetapkan.

</p>
<p class="para">Kegiatan ini terkait dengan program Renstra lima tahunan terutama pada rencana kerja bidang
pendidikan dan kemahasiswaan Prodi DIII Keperawatan (Kampus Curup) Poltekkes Kemenkes
Bengkulu pada program kerja peningkatan mutu input, proses dan output pendidikan dan
pengembangan sistem penjaminan mutu akademik. Adapun sasaran dari program kerja ini adalah
meningkatnya mutu akademik dan adanya penjaminan mutu meliputi standar isi (Kerangka dasar dan
struktur kurikulum, Standar perencanaan proses pembelajaran, standar kualifikasi akademik dosen,
standar penilaian hasil belajar oleh dosen, standar penelitian dan standar pengabdian masyarakat.
</p>
</div>

<div>
    <b>B. TUJUAN PEMERIKSAAN</b>
</div>
<div style="margin-left: 14pt;text-align: justify;">
    <ol>
    <li>Meneliti kepatuhan/ketaatan penjaminan mutu akademik internal tingkat poltekkes terhadap
standar isi (Kerangka dasar dan struktur kurikulum).</li>
    <li>Meneliti kesesuaian arah dan pelaksanaan penjaminan mutu akademik internal tingkat
Departemen terhadap Standar perencanaan proses pembelajaran di tingkat Prodi.</li>
    <li>Meneliti kepastian bahwa standar kualifikasi akademik dosen sesuai dengan yang ditetapkan oleh
Poltekkes (aturan akademik).</li>
    <li>Untuk memastikan standar penilaian hasil belajar oleh dosen sesuai dengan standar akademik
prodi.</li>
    <li>Untuk memastikan standar penelitian dan standar pengabdian masyarakat yang berlaku di Prodi
DIII Keperawatan (Kampus Curup) sesuai dengan standar tingkat Poltekkes Kemenkes Bengkulu.</li>

    </ol>
</div>

